import assert from 'node:assert/strict';
import {prepared, now, input} from './tron-review-test.ts';
import {deriveTronWallet} from '../src/wallet/tron.ts';
const module = await import('../src/tronTransferFlow.ts').catch(() => null);
assert.ok(module, 'TRON flow must separate preparation, signing and publication');
const wallet = deriveTronWallet('abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon abandon about');
let submissions = 0;
let clock = now;
let fail = true;
const payloads: unknown[] = [];
const flow = module.createTronTransferFlow({
  now: () => clock, prepare: async () => prepared,
  broadcast: async (_destination, payload) => { submissions++; payloads.push(payload); if (fail) throw new Error('CORS'); return {txid: payload.txid}; },
  status: async txId => ({chain: 'tron', network: 'mainnet', networkId: 'tron-mainnet', txId, state: 'unknown', solidified: false}),
});
await flow.prepare(input.sourceAddress, input.recipientAddress, input.amount);
assert.equal(flow.getSnapshot().phase, 'review');
assert.equal(flow.getSnapshot().signed, null);
assert.equal(submissions, 0);
assert.ok(Object.isFrozen(flow.getSnapshot().review));
const identity = flow.getSnapshot().review!.txId;
flow.sign(wallet.privateKey, 'watch-only');
assert.equal(flow.getSnapshot().signed, null, 'watch-only cannot sign');
flow.sign(wallet.privateKey, 'local-signing');
assert.equal(flow.getSnapshot().phase, 'signed');
assert.equal(flow.getSnapshot().signed!.txId, identity);
assert.equal(submissions, 0);
const bytes = flow.getSnapshot().signed!.rawTransactionHex;
const destination = {kind: 'tron-http' as const, endpoint: 'https://node.example'};
await flow.broadcast(destination);
assert.equal(flow.getSnapshot().phase, 'signed');
assert.equal(flow.getSnapshot().signed!.rawTransactionHex, bytes);
fail = false;
await flow.broadcast(destination);
assert.deepEqual(payloads[0], payloads[1], 'retry sends identical bytes');
assert.equal(flow.getSnapshot().phase, 'submitted');
assert.equal(flow.getSnapshot().status, null, 'submission is not execution');
await flow.checkStatus();
assert.equal(flow.getSnapshot().status!.state, 'unknown');
flow.reset();
await flow.prepare(input.sourceAddress, input.recipientAddress, input.amount);
flow.sign(wallet.privateKey, 'local-signing');
clock = Number(prepared.expirationMs);
await flow.broadcast(destination);
assert.equal(submissions, 2, 'expired bytes must not be sent or automatically rebuilt');
assert.equal(flow.getSnapshot().signed!.rawTransactionHex, bytes);
assert.equal(flow.getSnapshot().error, 'stale_preparation');
await flow.checkStatus();
assert.equal(flow.getSnapshot().status!.state, 'unknown');
assert.equal(flow.getSnapshot().error, 'expired_unknown', 'local expiry plus absent observation is not proof of rejection');
console.log('TRON flow: explicit review/sign/submit/status, watch-only, expiry, identical-byte retry passed.');

let resolvePrepare!: (value: typeof prepared) => void;
const pendingFlow = module.createTronTransferFlow({now: () => now, prepare: () => new Promise(resolve => {resolvePrepare = resolve;})});
const pending = pendingFlow.prepare(input.sourceAddress, input.recipientAddress, input.amount);
pendingFlow.reset();
resolvePrepare(prepared);
await pending;
assert.equal(pendingFlow.getSnapshot().review, null, 'changed intent must discard pending preparation');
assert.equal(pendingFlow.getSnapshot().phase, 'idle');
let resolveBroadcast!: (value: {txid: string}) => void;
let resolveStatus!: (value: unknown) => void;
const raced = module.createTronTransferFlow({now: () => now, prepare: async () => prepared,
  broadcast: () => new Promise(resolve => {resolveBroadcast = resolve;}),
  status: () => new Promise(resolve => {resolveStatus = resolve;})});
await raced.prepare(input.sourceAddress, input.recipientAddress, input.amount);
raced.sign(wallet.privateKey, 'local-signing');
const broadcastPending = raced.broadcast(destination);
const statusPending = raced.checkStatus();
raced.reset();
resolveBroadcast({txid: identity});
resolveStatus({txId: identity, state: 'executed-success'});
await Promise.all([broadcastPending, statusPending]);
assert.equal(raced.getSnapshot().phase, 'idle');
assert.equal(raced.getSnapshot().status, null, 'old wallet status must not leak into new flow');
console.log('TRON flow: stale async prepare/broadcast/status are discarded after intent or wallet invalidation.');
const expiredReview = module.createTronTransferFlow({now: () => clock, prepare: async () => prepared});
clock = now;
await expiredReview.prepare(input.sourceAddress, input.recipientAddress, input.amount);
clock = Number(prepared.expirationMs);
expiredReview.sign(wallet.privateKey, 'local-signing');
assert.equal(expiredReview.getSnapshot().signed, null);
assert.equal(expiredReview.getSnapshot().error, 'stale_preparation');
const mismatchFlow = module.createTronTransferFlow({now: () => now, prepare: async () => prepared, broadcast: async () => ({txid: '00'.repeat(32)})});
await mismatchFlow.prepare(input.sourceAddress, input.recipientAddress, input.amount);
mismatchFlow.sign('01'.padStart(64, '0'), 'local-signing');
assert.equal(mismatchFlow.getSnapshot().error, 'wallet_key_mismatch');
assert.equal(mismatchFlow.getSnapshot().signed, null);
mismatchFlow.sign(wallet.privateKey, 'local-signing');
await mismatchFlow.broadcast(destination);
assert.equal(mismatchFlow.getSnapshot().phase, 'signed', 'provider identity mismatch is not success');
assert.equal(mismatchFlow.getSnapshot().signed!.rawTransactionHex, bytes);
const tampered = module.createTronTransferFlow({now: () => now, prepare: async () => ({...prepared, contractAddress: wallet.address})});
await tampered.prepare(input.sourceAddress, input.recipientAddress, input.amount);
assert.equal(tampered.getSnapshot().review, null);
assert.equal(tampered.getSnapshot().error, 'prepared_transaction_mismatch');
